    MATRICULA.RA,
    ALUNO.NOME  AS NOME_ALUNO,
    CURSO.NOME AS NOME_CURSO
FROM MATRICULA 
    JOIN ALUNO ON MATRICULA.RA = ALUNO.RA
    JOIN CURSO ON MATRICULA.CURSO = CURSO.CODIGO
ORDER BY CURSO.NOME;

